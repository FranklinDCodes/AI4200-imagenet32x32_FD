def get_forward_metrics(model, input):

    yhat, stream = model(input, True)

    # get variances
    vars = list()
    for h in stream:
        vars.append(h.var(axis=1).mean().item())

    # get block stream ratios
    BSRs = list()
    block_input = stream[0]
    for h in stream[1:]:
        block_output_add = h - block_input
        ratio = block_output_add / block_input
        BSRs.append(((ratio**2).mean().item())**(0.5))
        block_input = h

    return vars, BSRs

# this function generated by Claude. See #5 in prompts.md
@torch.no_grad()
def block_grad_rms(model):
    """Call after loss.backward() and before optimizer.step().
    Returns a list of floats: the RMS of the gradient of fc2's parameters, one per block."""
    rms_per_block = []
    for block in model.blocks:
        grads = [block.fc2.weight.grad]
        if not grads:
            rms_per_block.append(torch.tensor(float("nan")))
            continue
        sq_sum = sum(g.float().pow(2).sum() for g in grads)
        n = sum(g.numel() for g in grads)
        rms_per_block.append((sq_sum / n).sqrt())
    # a single GPU->CPU sync at the end instead of one per block
    return torch.stack([r.cpu() for r in rms_per_block]).tolist()

# this function generated by Claude. See #5 in prompts.md
@torch.no_grad()
def snapshot_weights(model):
    """Call right before optimizer.step(). Stores detached copies of each block's fc1/fc2 weights."""
    return [
        [block.fc1.weight.detach().clone(), block.fc2.weight.detach().clone()]
        for block in model.blocks
    ]

# this function generated by Claude. See #5 in prompts.md
@torch.no_grad()
def relative_update_rms(model, before, eps=1e-12):
    """Call right after optimizer.step(). Returns a list of floats, one per block:
    RMS(delta W) / RMS(W_before), with RMS pooled over fc1 and fc2 together."""
    ratios = []
    for block, old_ws in zip(model.blocks, before):
        new_ws = [block.fc1.weight, block.fc2.weight]
        n = sum(w.numel() for w in old_ws)
        delta_sq = sum((new.float() - old.float()).pow(2).sum() for new, old in zip(new_ws, old_ws))
        w_sq = sum(old.float().pow(2).sum() for old in old_ws)
        delta_rms = (delta_sq / n).sqrt()
        w_rms = (w_sq / n).sqrt()
        ratios.append(delta_rms / (w_rms + eps))
    # single GPU->CPU sync at the end
    return torch.stack(ratios).cpu().tolist()

def get_backward_metrics(model, loss_fn, eval_x, eval_y, optim):

    logits = model(eval_x)           # forward pass
    loss = loss_fn(logits, eval_y)   # how wrong are we?

    optim.zero_grad()             # clear old gradients
    loss.backward()

    # get grads
    grads = block_grad_rms(model)

    # pre-update weights
    before = snapshot_weights(model)
    optim.step()             # clear old gradients

    # get step ratio
    update_ratios = relative_update_rms(model, before)

    return grads, update_ratios

# generated by Claude. See #4 in prompts.md
def plot_log_series(data, path, title="", xlabel="", ylabel=""):
    """Plot each list in `data` against its index (0, 1, 2, ...) on a log-scaled y axis
    and save the figure to `path`."""
    fig, ax = plt.subplots()

    for name, values in data.items():
        ax.plot(range(len(values)), values, label=name)

    ax.set_yscale("log")
    ax.set_title(title)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.legend()

    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)



def train(task, X_train, y_train, seed=0, device="cuda"):
    """Build a new model and train it from scratch. Returns the trained model."""
    torch.manual_seed(seed)                   # makes the run reproducible

    # 1. Build the model for this task. Only input size and class count differ.
    model = ResidualMLP(**TASKS[task]).to(device)

    eval_x = prepare(X_train[:1024]).to(device)
    eval_y = y_train[:1024]
    X_train = X_train[1024:]
    y_train = y_train[1024:]

    # 2. Wrap the data so we can loop over shuffled mini-batches.
    dataset = TensorDataset(prepare(X_train), torch.as_tensor(y_train).long())
    loader = DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=True)

    # create weights based on downscaled class count z scores
    t_counts = torch.unique(torch.as_tensor(y_train).long(), return_counts=True)[1]
    t_class_weights = 1 - (t_counts - t_counts.float().mean()) / t_counts.float().mean()
    print(f"Class counts: {t_counts.detach().cpu().numpy().tolist()}")
    print(f"Class weights: {t_class_weights.detach().cpu().numpy().tolist()}")

    # 3. Choose the loss and the optimizer.
    loss_fn = nn.CrossEntropyLoss(weight=t_class_weights.to(device))           # expects raw logits
    optimizer = torch.optim.AdamW(model.parameters(), lr=LEARNING_RATE)

    d_vars = dict() # variances
    d_bsrs = dict() # branch to stream ratios
    d_grads = dict() # grad rms
    d_wur = dict() # weight to update ratios
    d_vars["init"], d_bsrs["init"] = get_forward_metrics(model, eval_x)
    d_grads["init"], d_wur["init"] = get_backward_metrics(model, loss_fn, eval_x, eval_y, optimizer)

    # 4. The training loop.
    model.train()
    for epoch in range(EPOCHS[task]):

        # grab variance
        # if start or midpoint
        if epoch == (EPOCHS[task] + 1) // 2:
            d_vars["mid_training"], d_bsrs["mid_training"] = get_forward_metrics(model, eval_x)
            d_grads["mid_training"], d_wur["mid_training"] = get_backward_metrics(model, loss_fn, eval_x, eval_y, optimizer)

        total_loss = 0.0
        for X_batch, y_batch in loader:
            X_batch, y_batch = X_batch.to(device), y_batch.to(device)

            logits = model(X_batch)           # forward pass
            loss = loss_fn(logits, y_batch)   # how wrong are we?

            optimizer.zero_grad()             # clear old gradients
            loss.backward()                   # backward pass: compute gradients
            optimizer.step()                  # update the weights

            total_loss += loss.item() * len(X_batch)

        print(f"epoch {epoch + 1}: train loss {total_loss / len(dataset):.4f}")

    d_vars["final"], d_bsrs["final"] = get_forward_metrics(model, eval_x)
    d_grads["final"], d_wur["final"] = get_backward_metrics(model, loss_fn, eval_x, eval_y, optimizer)

    plot_log_series(d_vars, "plts/no_aug_variance.png", "Variance", "variance", "layer")
    plot_log_series(d_bsrs, "plts/no_aug_branch-stream_ratio.png", "Branch-stream ratio", "ratio", "layer")
    plot_log_series(d_grads, "plts/no_aug_grads.png", "Gradient RMS", "RMS", "layer")
    plot_log_series(d_wur, "plts/no_aug_update_ratio.png", "Update-weight ratio", "ratio", "layer")

    return model


def predict(model, X):
    """Return class probabilities for X, one row per example, on the CPU."""
    device = next(model.parameters()).device
    X = prepare(X)
    # Predict in chunks so a large test set does not run out of GPU memory.
    chunks = [model.predict(X[i:i + 1024].to(device)).cpu() for i in range(0, len(X), 1024)]
    return torch.cat(chunks)

